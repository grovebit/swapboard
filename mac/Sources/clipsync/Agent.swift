import AppKit
import ClipSyncCore
import Foundation

/// Polls the general pasteboard. It inspects `types` before reading any content, and reads
/// content only after the change count moves. Main thread only.
final class PasteboardWatcher {
    struct Change {
        let concealedOrTransient: Bool
        let frontmostApp: String?
    }

    var onChange: ((Change) -> Void)?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var ownChangeCount = -1
    private var timer: Timer?

    func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount, let types = pb.types else { return }
        guard !types.contains(Pasteboard.marker), types.contains(.string) else { return }
        let skip = types.contains(Pasteboard.concealed) || types.contains(Pasteboard.transient)
            || types.contains(Pasteboard.autoGenerated)
        onChange?(Change(concealedOrTransient: skip,
                         frontmostApp: NSWorkspace.shared.frontmostApplication?.bundleIdentifier))
    }

    func readString() -> String? { NSPasteboard.general.string(forType: .string) }

    func write(_ text: String, sensitive: Bool) {
        ownChangeCount = Pasteboard.write(text, sensitive: sensitive)
        lastChangeCount = ownChangeCount
    }
}

final class Agent {
    private let store = Paths.configStore
    private var config = Config()
    private let server = SyncServer()
    private let watcher = PasteboardWatcher()
    private let control = ControlServer()
    private var outbox = Outbox()
    private var recentIDs = RecentIDs()
    private var lastSent: AgentStatus.Event?
    private var lastReceived: AgentStatus.Event?
    private var lastReceivedText: String?
    /// Text last synced in either direction, used to suppress echoes and duplicate sends.
    private var lastSynced: (text: String, at: Date)?
    private var maintenance: Timer?
    private var signalSources: [DispatchSourceSignal] = []

    static func run() -> Never {
        let app = NSApplication.shared
        app.setActivationPolicy(.prohibited)
        let agent = Agent()
        do {
            try agent.start()
        } catch {
            Log.error("agent failed to start: \(error)")
            exit(1)
        }
        withExtendedLifetime(agent) { app.run() }
        exit(0)
    }

    private func start() throws {
        signal(SIGPIPE, SIG_IGN)
        try Paths.ensureDataDir()
        trimLog()
        config = store.load()
        if config.pruneExpired() { try? store.save(config) }

        server.lookupPSK = { [weak self] pid in self?.psk(for: pid) }
        server.onEstablished = { [weak self] peer in self?.peerEstablished(peer) }
        server.onMessage = { [weak self] peer, message in self?.handle(message, from: peer) }
        server.start(port: config.settings.port)

        watcher.onChange = { [weak self] change in self?.localCopy(change) }
        watcher.start()

        try control.start(path: Paths.socketPath) { [weak self] request in
            self?.handleControl(request) ?? .error("agent shutting down")
        }

        maintenance = Timer.scheduledTimer(withTimeInterval: 15, repeats: true) { [weak self] _ in
            self?.runMaintenance()
        }

        for sig in [SIGTERM, SIGINT] {
            signal(sig, SIG_IGN)
            let source = DispatchSource.makeSignalSource(signal: sig, queue: .main)
            source.setEventHandler { [weak self] in
                Log.info("agent stopping")
                self?.control.stop()
                self?.server.stop()
                exit(0)
            }
            source.resume()
            signalSources.append(source)
        }
        Log.info("agent started (\(config.pairings.count) pairing(s), auto-sync \(config.settings.paused ? "paused" : "on"))")
    }

    // MARK: - Pairings

    private func psk(for pid: String) -> Data? {
        if let key = config.psk(for: pid) { return key }
        config = store.load() // `clipsync pair` may have just added it
        return config.psk(for: pid)
    }

    private func peerEstablished(_ peer: Peer) {
        guard let pid = peer.pid else { return }
        for other in server.established where other !== peer && other.pid == pid {
            other.close(.replaced)
        }
        var newlyPaired = false
        config = (try? store.update { config in
            guard let index = config.pairings.firstIndex(where: { $0.pid == pid }) else { return }
            newlyPaired = !config.pairings[index].confirmed
            config.pairings[index].confirmed = true
            config.pairings[index].expires = nil
            config.pairings[index].device = peer.device
            config.pairings[index].lastSeen = Date()
            if newlyPaired {
                // Re-pairing the same phone replaces its old pairing.
                config.pairings.removeAll { $0.pid != pid && $0.confirmed && $0.device == peer.device }
            }
        }) ?? store.load()
        Log.info("\(peer.device) connected via \(Route.name(for: peer.host)) (\(peer.host) on \(peer.interfaceNames))")
        if newlyPaired {
            try? FileManager.default.removeItem(at: Paths.qrURL)
            AlfredNotifier.notify("📱 Paired with \(peer.device)")
        }
        if let clip = outbox.freshPending() { peer.send(.clip(clip)) }
    }

    // MARK: - Sync

    private func handle(_ message: Message, from peer: Peer) {
        switch message {
        case let .clip(clip):
            receive(clip, from: peer)
        case let .ack(id):
            outbox.acknowledge(id)
            if lastSent?.id == id { lastSent?.delivered = true }
        default:
            break
        }
    }

    private func receive(_ clip: Clip, from peer: Peer) {
        defer { peer.send(.ack(id: clip.id)) }
        guard recentIDs.insert(clip.id), clip.text.utf8.count <= ProtocolConstants.maxClipBytes else { return }
        watcher.write(clip.text, sensitive: clip.sensitive)
        lastSynced = (clip.text, Date())
        lastReceivedText = clip.text
        lastReceived = AgentStatus.Event(id: clip.id, at: Date(), device: peer.device,
                                         preview: preview(clip.text, sensitive: clip.sensitive),
                                         sensitive: clip.sensitive, delivered: true)
        // The phone now has the newest content; don't later overwrite it with an older Mac clip.
        if let pending = outbox.pending { outbox.acknowledge(pending.clip.id) }
        Log.info("received \(clip.text.utf8.count) bytes from \(peer.device)\(clip.sensitive ? " (sensitive)" : "")")
        if config.settings.notifyOnReceive {
            AlfredNotifier.notify("📋 From \(peer.device): \(preview(clip.text, sensitive: clip.sensitive, limit: 80))")
        }
    }

    private func localCopy(_ change: PasteboardWatcher.Change) {
        let settings = config.settings
        guard !settings.paused, !config.pairings.isEmpty else { return }
        if change.concealedOrTransient {
            Log.info("skipped a concealed/transient copy")
            return
        }
        if let app = change.frontmostApp, settings.ignoredApps.contains(app) {
            Log.info("skipped a copy from ignored app \(app)")
            return
        }
        guard let text = watcher.readString(), !text.isEmpty else { return }
        guard text.utf8.count <= settings.maxClipBytes else {
            Log.info("skipped a copy of \(text.utf8.count) bytes (limit \(settings.maxClipBytes))")
            return
        }
        if let last = lastSynced, last.text == text, Date().timeIntervalSince(last.at) < 600 { return }
        _ = send(text, sensitive: false)
    }

    /// Queues the clip and sends it to every connected phone. Returns the receiving device, if any.
    private func send(_ text: String, sensitive: Bool) -> String? {
        let clip = Clip(text: text, sensitive: sensitive)
        outbox.put(clip)
        lastSynced = (text, Date())
        let targets = server.established
        lastSent = AgentStatus.Event(id: clip.id, at: Date(), device: targets.first?.device,
                                     preview: preview(text, sensitive: sensitive),
                                     sensitive: sensitive, delivered: false)
        for peer in targets { peer.send(.clip(clip)) }
        Log.info("sent \(text.utf8.count) bytes to \(targets.count) phone(s)\(sensitive ? " (sensitive)" : "")")
        return targets.first?.device
    }

    // MARK: - Control

    private func handleControl(_ request: ControlRequest) -> ControlResponse {
        switch request.cmd {
        case "ping":
            return ControlResponse(ok: true)
        case "status":
            return ControlResponse(ok: true, status: status())
        case "send":
            guard let text = request.text, !text.isEmpty else { return .error("Clipboard has no text") }
            guard text.utf8.count <= ProtocolConstants.maxClipBytes else {
                return .error("Too large to send (\(text.utf8.count / 1024) KB, limit 1024 KB)")
            }
            guard !config.pairings.isEmpty else { return .error("No phone paired yet. Choose “Pair a phone” first") }
            if let device = send(text, sensitive: request.sensitive ?? false) {
                return ControlResponse(ok: true, message: "Sent to \(device)")
            }
            return ControlResponse(ok: true, message: "Phone not connected; will deliver if it reconnects within 5 min")
        case "pause", "resume":
            let paused = request.cmd == "pause"
            config = (try? store.update { $0.settings.paused = paused }) ?? config
            return ControlResponse(ok: true, message: paused ? "Auto-sync paused" : "Auto-sync resumed")
        case "last":
            guard let text = lastReceivedText else { return .error("Nothing received from the phone yet") }
            return ControlResponse(ok: true, text: text, sensitive: lastReceived?.sensitive ?? false)
        case "reload":
            reload()
            return ControlResponse(ok: true)
        default:
            return .error("unknown command \(request.cmd)")
        }
    }

    private func reload() {
        let oldPort = config.settings.port
        config = store.load()
        let valid = Set(config.pairings.map(\.pid))
        for peer in server.peers where peer.pid.map({ !valid.contains($0) }) ?? false {
            peer.close(.authFailed) // unpaired
        }
        if config.settings.port != oldPort {
            Log.info("port changed to \(config.settings.port)")
            server.start(port: config.settings.port)
        }
    }

    private func status() -> AgentStatus {
        AgentStatus(
            paused: config.settings.paused,
            port: config.settings.port,
            listening: server.listening,
            listenError: server.listenError,
            peers: server.established.map {
                AgentStatus.Peer(pid: $0.pid ?? "", device: $0.device, host: $0.host,
                                 route: Route.name(for: $0.host), since: $0.connectedAt)
            },
            lastSent: lastSent,
            lastReceived: lastReceived,
            pairingPending: config.pairings.contains { !$0.confirmed }
        )
    }

    // MARK: - Housekeeping

    private func runMaintenance() {
        let now = Date()
        for peer in server.peers where now.timeIntervalSince(peer.lastInbound) > ProtocolConstants.serverIdleTimeout {
            Log.info("closing idle connection from \(peer.host)")
            peer.close(.normal)
        }
        var fresh = store.load()
        if fresh.pruneExpired(now: now) {
            try? store.save(fresh)
            Log.info("expired an unused pairing QR code")
        }
        config = fresh
        if !config.pairings.contains(where: { !$0.confirmed }) {
            try? FileManager.default.removeItem(at: Paths.qrURL)
        }
        server.maintain()
    }

    private func trimLog() {
        let attributes = try? FileManager.default.attributesOfItem(atPath: Paths.logURL.path)
        if let size = attributes?[.size] as? NSNumber, size.intValue > 2 * 1024 * 1024 {
            ftruncate(STDERR_FILENO, 0)
        }
    }
}

enum AlfredNotifier {
    /// Shows a banner through the workflow's External Trigger "notify". Text is passed as argv, never
    /// interpolated into AppleScript source.
    static func notify(_ text: String) {
        let script = """
        on run argv
            tell application id "com.runningwithcrayons.Alfred" to run trigger "notify" in workflow (item 1 of argv) with argument (item 2 of argv)
        end run
        """
        Shell.spawn("/usr/bin/osascript", ["-e", script, Paths.bundleID, text])
    }
}
