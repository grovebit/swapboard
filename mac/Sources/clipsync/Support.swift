}

enum Shell {
    @discardableResult
    static func run(_ path: String, _ args: [String]) -> (status: Int32, output: String) {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: path)
        process.arguments = args
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        do { try process.run() } catch { return (-1, "\(error)") }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        return (process.terminationStatus, String(decoding: data, as: UTF8.self))
    }

    /// Starts a process without waiting for it (e.g. Quick Look, Console).
    static func spawn(_ path: String, _ args: [String]) {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: path)
        process.arguments = args
        process.standardOutput = FileHandle.nullDevice
        process.standardError = FileHandle.nullDevice
        try? process.run()
    }
}

enum MacInfo {
    static var computerName: String {
        if let name = SCDynamicStoreCopyComputerName(nil, nil) as String?, !name.isEmpty { return name }
        return Host.current().localizedName ?? "Mac"
    }

    static var localHostName: String? {
        SCDynamicStoreCopyLocalHostName(nil) as String?
    }

    /// This Mac's Tailscale IPv4 addresses (100.64.0.0/10). ClipSync only ever uses Tailscale:
    /// it never listens on, or hands out, LAN addresses.
    static func tailscaleIPv4s() -> [String] {
        var addresses: [String] = []
        var ifaddrPtr: UnsafeMutablePointer<ifaddrs>?
        guard getifaddrs(&ifaddrPtr) == 0, let first = ifaddrPtr else { return [] }
        defer { freeifaddrs(ifaddrPtr) }
        for pointer in sequence(first: first, next: { $0.pointee.ifa_next }) {
            let ifa = pointer.pointee
            let flags = Int32(ifa.ifa_flags)
            guard let addr = ifa.ifa_addr, addr.pointee.sa_family == UInt8(AF_INET),
                  flags & IFF_UP != 0, flags & IFF_RUNNING != 0
            else { continue }
            var host = [CChar](repeating: 0, count: Int(NI_MAXHOST))
            guard getnameinfo(addr, socklen_t(addr.pointee.sa_len), &host, socklen_t(host.count),
                              nil, 0, NI_NUMERICHOST) == 0 else { continue }
            let ip = String(cString: host)
            if Route.isTailscale(ip), !addresses.contains(ip) { addresses.append(ip) }
        }
        return addresses
    }
}

enum Route {
    static func octets(_ ip: String) -> [Int]? {
        let parts = ip.split(separator: ".").compactMap { Int($0) }
        return parts.count == 4 ? parts : nil
    }

    static func isTailscale(_ ip: String) -> Bool {
        guard let o = octets(ip) else { return false }
        return o[0] == 100 && (64...127).contains(o[1])
    }

    static func name(for ip: String) -> String { isTailscale(ip) ? "Tailscale" : "unknown network" }
}

enum Pasteboard {
    static let marker = NSPasteboard.PasteboardType("com.clipsync.remote")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// Writes text marked as coming from ClipSync (and concealed if sensitive). Returns the new changeCount.
    @discardableResult
    static func write(_ text: String, sensitive: Bool) -> Int {
        let pb = NSPasteboard.general
        var types: [NSPasteboard.PasteboardType] = [.string, marker]
        if sensitive { types.append(concealed) }
        pb.declareTypes(types, owner: nil)
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: marker)
        if sensitive { pb.setData(Data(), forType: concealed) }
        return pb.changeCount
    }

    static func readText() -> (text: String, concealed: Bool)? {
        let pb = NSPasteboard.general
        guard let text = pb.string(forType: .string) else { return nil }
        return (text, pb.types?.contains(concealed) ?? false)
    }
}

func preview(_ text: String, sensitive: Bool, limit: Int = 60) -> String {
    if sensitive { return "•••••• (sensitive)" }
    let oneLine = text.replacingOccurrences(of: "\r\n", with: " ⏎ ").replacingOccurrences(of: "\n", with: " ⏎ ")
        .trimmingCharacters(in: .whitespaces)
    return oneLine.count > limit ? String(oneLine.prefix(limit)) + "…" : oneLine
}

func relativeTime(_ date: Date, now: Date = Date()) -> String {
    let seconds = Int(now.timeIntervalSince(date))
    switch seconds {
    case ..<10: return "just now"
    case ..<60: return "\(seconds)s ago"
    case ..<3600: return "\(seconds / 60)m ago"
    case ..<86400: return "\(seconds / 3600)h ago"
    default: return "\(seconds / 86400)d ago"
    }
}
