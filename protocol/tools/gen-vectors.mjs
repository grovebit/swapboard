// Generates protocol/vectors.json deterministically with Node's crypto.
// Node acts as an independent reference implementation of PROTOCOL.md.
// Usage: node protocol/tools/gen-vectors.mjs
import { hkdfSync, createCipheriv } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import assert from 'node:assert/strict';

const hex = (b) => Buffer.from(b).toString('hex');
const b64u = (b) => Buffer.from(b).toString('base64url');
const seq = (start, n) => Buffer.from(Array.from({ length: n }, (_, i) => (start + i) & 0xff));
const hkdf = (ikm, salt, info, len) => Buffer.from(hkdfSync('sha256', ikm, salt, info, len));

// --- RFC 5869 test case 1 -------------------------------------------------
const rfc = {
  ikm: Buffer.alloc(22, 0x0b),
  salt: Buffer.from('000102030405060708090a0b0c', 'hex'),
  info: Buffer.from('f0f1f2f3f4f5f6f7f8f9', 'hex'),
  length: 42,
};
const rfcOkm = hkdf(rfc.ikm, rfc.salt, rfc.info, rfc.length);
assert.equal(
  hex(rfcOkm),
  '3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865',
  'Node HKDF does not match RFC 5869 case 1',
);

// --- Session --------------------------------------------------------------
const psk = seq(0x00, 32);
const nc = seq(0xa0, 16);
const ns = seq(0xb0, 16);
const salt = Buffer.concat([nc, ns]);
const kC2S = hkdf(psk, salt, Buffer.from('swapboard v1 c2s'), 32);
const kS2C = hkdf(psk, salt, Buffer.from('swapboard v1 s2c'), 32);
const AAD = Buffer.from('swapboard-v1');

function seal(key, counter, plaintext) {
  const ctr = Buffer.alloc(8);
  ctr.writeBigUInt64BE(BigInt(counter));
  const nonce = Buffer.concat([Buffer.alloc(4), ctr]);
  const cipher = createCipheriv('aes-256-gcm', key, nonce);
  cipher.setAAD(AAD);
  const ct = Buffer.concat([cipher.update(Buffer.from(plaintext, 'utf8')), cipher.final()]);
  return Buffer.concat([ctr, ct, cipher.getAuthTag()]);
}

const clipId = '6f1c2a9e-3b4d-4e5f-8a7b-9c0d1e2f3a4b';
const frameSpecs = [
  ['c2s', 0, '{"type":"auth","device":"Test Phone"}'],
  ['s2c', 0, '{"type":"welcome","mac":"Test Mac"}'],
  ['c2s', 1, `{"type":"clip","id":"${clipId}","text":"Hello from Android 👋\\nLine 2 — ünïcödé","sensitive":false,"ts":1763800000000}`],
  ['s2c', 1, `{"type":"ack","id":"${clipId}"}`],
  ['s2c', 2, '{"type":"clip","id":"0a1b2c3d-4e5f-4a6b-8c7d-8e9f0a1b2c3d","text":"secret from Mac","sensitive":true,"ts":1763800001000}'],
  ['c2s', 2, '{"type":"ping"}'],
  ['s2c', 3, '{"type":"pong"}'],
];
const keyFor = (dir) => (dir === 'c2s' ? kC2S : kS2C);
const frames = frameSpecs.map(([direction, counter, plaintext]) => ({
  direction,
  counter,
  plaintext,
  frame_hex: hex(seal(keyFor(direction), counter, plaintext)),
}));

// --- Frames that must be rejected ------------------------------------------
const clipFrame = Buffer.from(frames[2].frame_hex, 'hex'); // c2s, counter 1
const tampered = Buffer.from(clipFrame);
tampered[tampered.length - 1] ^= 0x01;
const invalid_frames = [
  { reason: 'tampered tag', direction: 'c2s', expected_counter: 1, frame_hex: hex(tampered) },
  { reason: 'replayed counter', direction: 'c2s', expected_counter: 2, frame_hex: hex(clipFrame) },
  { reason: 'skipped counter', direction: 'c2s', expected_counter: 2, frame_hex: hex(seal(kC2S, 3, '{"type":"ping"}')) },
  { reason: 'wrong direction key', direction: 'c2s', expected_counter: 0, frame_hex: frames[1].frame_hex },
  { reason: 'truncated', direction: 'c2s', expected_counter: 0, frame_hex: hex(clipFrame.subarray(0, 20)) },
];

// --- Pairing URI -----------------------------------------------------------
const pid = b64u(seq(0x00, 12));
const pairing = {
  pid,
  name: 'Test Mac + Ü',
  psk: b64u(psk),
  hosts: ['100.101.102.103', '192.168.1.20', 'test-mac.local'],
  port: 48613,
};
const enc = (s) => encodeURIComponent(s); // encodes space as %20 and + as %2B
const uri =
  `swapboard://pair?v=1&pid=${pairing.pid}&name=${enc(pairing.name)}&k=${pairing.psk}` +
  `&h=${pairing.hosts.map(enc).join(',')}&p=${pairing.port}`;

const vectors = {
  description: 'Swapboard protocol v1 test vectors. Generated by protocol/tools/gen-vectors.mjs — do not edit by hand.',
  hkdf_rfc5869_case1: {
    ikm: hex(rfc.ikm),
    salt: hex(rfc.salt),
    info: hex(rfc.info),
    length: rfc.length,
    okm: hex(rfcOkm),
  },
  session: {
    psk: b64u(psk),
    nc: b64u(nc),
    ns: b64u(ns),
    salt_hex: hex(salt),
    k_c2s_hex: hex(kC2S),
    k_s2c_hex: hex(kS2C),
    aad: AAD.toString('ascii'),
  },
  frames,
  invalid_frames,
  pairing_uri: { uri, ...pairing },
};

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'vectors.json');
writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
console.log(`wrote ${out}`);
